#!/usr/bin/env python3
"""Turn the Overpass dump (osm/raw.json) into src/osm.js: projected, simplified street map data.
Map data © OpenStreetMap contributors, ODbL."""
import json, math, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
LAT0, LON0 = 53.345, -6.265
KX, KY = 111320 * math.cos(math.radians(LAT0)), 110574

def proj(lat, lon):
    return ((lon - LON0) * KX, -(lat - LAT0) * KY)

def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    def rec(a, b):
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1e-9
        best, bi = 0, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / L
            if d > best:
                best, bi = d, i
        if best > tol:
            return rec(a, bi)[:-1] + rec(bi, b)
        return [pts[a], pts[b]]
    return rec(0, len(pts) - 1)

def flat(pts):
    out = []
    for x, y in pts:
        out += [round(x), round(y)]
    return out

def length(pts):
    return sum(math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]) for i in range(len(pts) - 1))

CLS = {}
for k in ('motorway', 'trunk', 'primary', 'motorway_link', 'trunk_link', 'primary_link'): CLS[k] = 'major'
for k in ('secondary', 'secondary_link'): CLS[k] = 'sec'
for k in ('tertiary', 'tertiary_link'): CLS[k] = 'ter'
for k in ('unclassified', 'residential', 'living_street'): CLS[k] = 'res'
for k in ('pedestrian',): CLS[k] = 'ped'
for k in ('footway', 'path', 'steps'): CLS[k] = 'foot'

data = json.load(open(ROOT / 'osm' / 'raw.json'))
roads = {c: [] for c in ('major', 'sec', 'ter', 'res', 'ped', 'foot')}
labels, river, canal, parks, tram = [], [], [], [], []

def geom(el):
    return [proj(p['lat'], p['lon']) for p in el.get('geometry', []) if p]

for el in data['elements']:
    t = el.get('tags', {})
    if el['type'] == 'relation':
        for m in el.get('members', []):
            if m.get('role') == 'outer' and m.get('geometry'):
                pts = [proj(p['lat'], p['lon']) for p in m['geometry']]
                if len(pts) > 3 and pts[0] == pts[-1]:
                    parks.append(flat(simplify(pts, 3)))
        continue
    pts = geom(el)
    if len(pts) < 2:
        continue
    if 'highway' in t:
        if t.get('tunnel') in ('yes', 'culvert') or t.get('access') == 'private':
            continue
        c = CLS.get(t['highway'])
        if not c:
            continue
        sp = simplify(pts, 1.5)
        roads[c].append(flat(sp))
        name = t.get('name')
        L = length(pts)
        if name and L > 45:
            # Candidate label spots along the way, middle first.
            cands = []
            for frac in ((0.5,) if L < 160 else (0.5, 0.3, 0.7, 0.15, 0.85)):
                target, acc = L * frac, 0
                for i in range(len(pts) - 1):
                    seg = math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1])
                    if acc + seg >= target:
                        f = (target - acc) / (seg or 1)
                        x = pts[i][0] + f * (pts[i + 1][0] - pts[i][0])
                        y = pts[i][1] + f * (pts[i + 1][1] - pts[i][1])
                        ang = math.degrees(math.atan2(pts[i + 1][1] - pts[i][1], pts[i + 1][0] - pts[i][0]))
                        if ang > 90: ang -= 180
                        if ang < -90: ang += 180
                        cands += [round(x), round(y), round(ang)]
                        break
                    acc += seg
            labels.append([name, c, cands, round(L)])
    elif t.get('waterway') == 'river' and t.get('tunnel') not in ('yes', 'culvert'):
        (river if t.get('name') == 'Liffey' else canal).append(flat(simplify(pts, 3)))
    elif t.get('waterway') == 'canal' and t.get('tunnel') not in ('yes', 'culvert'):
        canal.append(flat(simplify(pts, 3)))
    elif t.get('leisure') in ('park', 'garden'):
        if pts[0] == pts[-1] and len(pts) > 3:
            area = abs(sum(pts[i][0] * pts[i + 1][1] - pts[i + 1][0] * pts[i][1] for i in range(len(pts) - 1))) / 2
            if area > 1500:
                parks.append(flat(simplify(pts, 2)))
    elif t.get('railway') == 'tram':
        tram.append(flat(simplify(pts, 3)))

# Keep the longest label per street name within 300 m of each other.
rank = {'major': 0, 'sec': 1, 'ter': 2, 'ped': 3, 'res': 4, 'foot': 5}
labels.sort(key=lambda l: (-l[3]))
kept = []
for l in labels:
    if any(k[0] == l[0] and math.hypot(k[2][0] - l[2][0], k[2][1] - l[2][1]) < 300 for k in kept):
        continue
    kept.append(l)
kept.sort(key=lambda l: (rank[l[1]], -l[3]))
out = {'roads': roads, 'labels': [l[:3] for l in kept], 'river': river, 'canal': canal, 'parks': parks, 'tram': tram}
js = '// Generated by osm/process.py from OpenStreetMap data. © OpenStreetMap contributors, ODbL.\nconst OSM = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n'
(ROOT / 'src' / 'osm.js').write_text(js)
print({k: len(v) for k, v in roads.items()}, 'labels', len(kept), 'river', len(river), 'canal', len(canal), 'parks', len(parks), 'tram', len(tram), 'KB', len(js) // 1024)
