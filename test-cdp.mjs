// Headless smoke test over the Chrome DevTools Protocol: loads the PWA, exercises the plan, screenshots each tab.
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const OUT = new URL('./test-out/', import.meta.url).pathname;
const dark = process.argv.includes('--dark');
const chrome = spawn('chromium', ['--headless=new', '--remote-debugging-port=9333', '--no-first-run', '--user-data-dir=' + OUT + 'profile' + (dark ? '-d' : ''), 'about:blank'], { stdio: 'ignore' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
let ws, id = 0; const pending = new Map(); const logs = [];
for (let i = 0; i < 40; i++) { try { const r = await fetch('http://127.0.0.1:9333/json'); const t = (await r.json()).find(x => x.type === 'page'); if (t) { ws = new WebSocket(t.webSocketDebuggerUrl); break; } } catch {} await sleep(250); }
await new Promise(r => ws.onopen = r);
ws.onmessage = m => { const d = JSON.parse(m.data); if (d.id && pending.has(d.id)) { pending.get(d.id)(d); pending.delete(d.id); }
  if (d.method === 'Runtime.consoleAPICalled') logs.push(d.params.type + ': ' + d.params.args.map(a => a.value ?? a.description).join(' '));
  if (d.method === 'Runtime.exceptionThrown') logs.push('EXC: ' + JSON.stringify(d.params.exceptionDetails.exception?.description || d.params.exceptionDetails.text)); };
const send = (method, params = {}) => new Promise(r => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async expr => { const r = await send('Runtime.evaluate', { expression: expr, awaitPromise: true, returnByValue: true }); if (r.result.exceptionDetails) logs.push('EVAL ERR ' + expr.slice(0, 60) + ': ' + r.result.exceptionDetails.exception?.description); return r.result.result?.value; };
const shot = async name => { const r = await send('Page.captureScreenshot', { format: 'png' }); writeFileSync(OUT + name + '.png', Buffer.from(r.result.data, 'base64')); };
await send('Runtime.enable'); await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: dark ? 'dark' : 'light' }] });
await send('Page.navigate', { url: 'http://127.0.0.1:8791/' }); await sleep(1500);
const sfx = dark ? '-dark' : '';
await shot('1-explore-first' + sfx);
await ev(`document.querySelector('[data-act=hotel][data-id=christchurch]').click()`);
await ev(`document.querySelector('[data-tab=plan]').click()`); await sleep(200);
await ev(`document.querySelector('[data-act=tpl][data-i="0"]').click()`); await sleep(200);
await shot('2-plan-jue' + sfx);
console.log('jue rows', await ev(`document.querySelectorAll('.tl-stop').length`), 'end', await ev(`document.querySelector('.totals').innerText.replace(/\\n/g,' ')`));
console.log('pills', await ev(`[...document.querySelectorAll('.tl-stop .pill')].map(p=>p.innerText).join(' | ')`));
await ev(`document.querySelector('[data-act=opt]').click()`); await sleep(200);
console.log('after opt', await ev(`[...document.querySelectorAll('.sname')].map(p=>p.innerText).join(' > ')`));
await ev(`document.querySelector('[data-act=day][data-day=sab]').click()`); await sleep(100);
await ev(`document.querySelector('[data-act=tpl][data-i="0"]').click()`); await sleep(100);
await ev(`document.querySelector('[data-act=dur][data-i="2"][data-v="15"]').click()`);
await ev(`document.querySelector('[data-act=dur][data-i="2"][data-v="15"]').click()`); await sleep(100);
console.log('sab limit', await ev(`(document.querySelector('.limitmsg')||{}).innerText`));
await shot('3-plan-sab' + sfx);
await ev(`document.querySelector('[data-act=mapday]').click()`); await sleep(600);
await shot('4-map-sab' + sfx);
await ev(`document.querySelector('[data-act=mapmode][data-day=all]').click()`); await sleep(300);
await shot('5-map-all' + sfx);
await ev(`document.querySelector('[data-tab=explore]').click()`); await sleep(100);
await ev(`(()=>{const q=document.querySelector('#q');q.value='gratis lluvia';q.dispatchEvent(new Event('input'))})()`); await sleep(100);
console.log('search "gratis lluvia":', await ev(`[...document.querySelectorAll('.item-name')].map(x=>x.innerText).join(', ')`));
await ev(`(()=>{const q=document.querySelector('#q');q.value='pinta';q.dispatchEvent(new Event('input'))})()`); await sleep(100);
console.log('search "pinta":', await ev(`[...document.querySelectorAll('.item-name')].map(x=>x.innerText).slice(0,6).join(', ')`));
await ev(`(()=>{const q=document.querySelector('#q');q.value='';q.dispatchEvent(new Event('input'))})()`);
await ev(`document.querySelector('[data-act=open][data-id=guinness]').click()`); await sleep(200);
await shot('6-detail' + sfx);
await ev(`document.querySelector('#sheet-close').click()`); await sleep(300);
console.log('sheet hidden after close', await ev(`document.querySelector('#sheet').hidden`));
await ev(`document.querySelector('[data-tab=info]').click()`); await sleep(100);
await ev(`document.querySelector('[data-act=export]').click()`); await sleep(200);
const code = await ev(`document.querySelector('#io').value`);
console.log('export len', code.length, code.slice(0, 20));
await ev(`document.querySelector('[data-act=import]').click()`); await sleep(100);
await shot('7-info' + sfx);
console.log('overflow-x', await ev(`document.documentElement.scrollWidth > innerWidth || document.body.scrollWidth > innerWidth`));
await sleep(1500);
console.log('sw controller', await ev(`!!navigator.serviceWorker.controller`), 'caches', await ev(`caches.keys().then(k=>k.join(','))`));
console.log('LOGS:\n' + logs.join('\n'));
ws.close(); chrome.kill(); (await import('node:child_process')).spawnSync('pkill', ['-f', '[r]emote-debugging-port=93']);
process.exit(0);
